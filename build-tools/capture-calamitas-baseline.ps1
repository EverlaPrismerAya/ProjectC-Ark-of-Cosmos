param([string]$SourceRoot = (Join-Path $PSScriptRoot '../../_calamity_public'))
$ErrorActionPreference = 'Stop'
$revision = '1a8cebd27ec5615316b78f71973446b5528d2b78'
$workspace = Split-Path $PSScriptRoot -Parent
$source = (Resolve-Path -LiteralPath $SourceRoot).Path
$head = git -C $source rev-parse HEAD
if ($LASTEXITCODE -ne 0 -or $head -ne $revision) { throw "Expected Calamity revision $revision, got $head" }
if (git -C $source status --porcelain) { throw 'The reference checkout must be clean.' }
$output = Join-Path $workspace 'reference/supreme-calamitas'
New-Item -ItemType Directory -Force -Path $output | Out-Null
$paths = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
$pending = [System.Collections.Generic.Queue[string]]::new()
Get-ChildItem -LiteralPath (Join-Path $source 'NPCs/SupremeCalamitas') -Filter '*.cs' | ForEach-Object {
    $pending.Enqueue('NPCs/SupremeCalamitas/' + $_.Name)
}
# Follow projectile descendants as well as direct emissions. Alternate seed-only references
# remain in the evidence; they are not automatically part of the ordinary death-mode port.
$projectileIndex = @{}
Get-ChildItem -LiteralPath (Join-Path $source 'Projectiles') -Recurse -Filter '*.cs' | ForEach-Object {
    $projectileIndex[$_.BaseName] = [IO.Path]::GetRelativePath($source, $_.FullName).Replace('\', '/')
}
while ($pending.Count -gt 0) {
    $path = $pending.Dequeue()
    if (-not $paths.Add($path)) { continue }
    $text = [IO.File]::ReadAllText((Join-Path $source $path))
    foreach ($match in [regex]::Matches($text, 'ProjectileType<([\w.]+)>')) {
        $name = ($match.Groups[1].Value -split '\.')[-1]
        if ($projectileIndex.ContainsKey($name)) { $pending.Enqueue($projectileIndex[$name]) }
    }
}
[void]$paths.Add('Effects/HellBall.fx')
[void]$paths.Add('Effects/SupremeShieldShader.fx')
[void]$paths.Add('Systems/Mechanic/ArenaWallSystem.cs')
[void]$paths.Add('Utilities/NPCUtils.cs')
$manifest = @()
$evidence = [System.Collections.Generic.List[string]]::new()
$evidence.Add("# Calamitas source evidence: $revision")
$evidence.Add('Generated by build-tools/capture-calamitas-baseline.ps1. Line numbers refer to pinned upstream files. Includes alternate-seed branches; interpret surrounding source before porting.')
foreach ($path in ($paths | Sort-Object)) {
    $original = Join-Path $source $path
    if (-not (Test-Path -LiteralPath $original)) { throw "Missing baseline source: $path" }
    $target = Join-Path $output ('source/' + $path)
    New-Item -ItemType Directory -Force -Path (Split-Path $target -Parent) | Out-Null
    Copy-Item -LiteralPath $original -Destination $target -Force
    $manifest += [ordered]@{ path = $path; sha256 = (Get-FileHash -LiteralPath $original -Algorithm SHA256).Hash.ToLowerInvariant() }
    $evidence.Add("`n## $path")
    $lines = [IO.File]::ReadAllLines($original)
    for ($i = 0; $i -lt $lines.Length; $i++) {
        if ($lines[$i] -match 'death|revenge|expertMode|NewProjectile|NewNPC|ProjectileType<|NPCType<|Colliding|CanHit|OnKill|timeLeft|extraUpdates|lifeMax|IsAtHp|IsAtSep|IsAtBrothers|FinishedBH|BulletHellDuration|attackCastDelay|hasSummoned|CheckDead') {
            $evidence.Add(('{0}: {1}' -f ($i + 1), $lines[$i].Trim()))
        }
    }
}
[IO.File]::WriteAllText((Join-Path $output 'source-manifest.json'), ([ordered]@{revision=$revision; files=$manifest} | ConvertTo-Json -Depth 8))
[IO.File]::WriteAllLines((Join-Path $output 'source-evidence.md'), $evidence)
# Read-only hash inventory before any new runtime resources are copied.
$runtimeHashes = @{}
Get-ChildItem -LiteralPath (Join-Path $workspace 'src/main/resources') -Recurse -File | ForEach-Object {
    $hash = (Get-FileHash -LiteralPath $_.FullName -Algorithm SHA256).Hash.ToLowerInvariant()
    $runtimeHashes[$hash] = @($runtimeHashes[$hash]) + [IO.Path]::GetRelativePath($workspace, $_.FullName).Replace('\', '/')
}
$assets = @()
$assetPaths = @('NPCs/SupremeCalamitas/BrimstoneHeart.png', 'ExtraTextures/ScreamyFace.png', 'ExtraTextures/SoulVortex.png', 'NPCs/SupremeCalamitas/ForcefieldTexture.png')
$assetPaths += Get-ChildItem -LiteralPath (Join-Path $source 'Sounds/Custom/SCalSounds') -File | ForEach-Object { 'Sounds/Custom/SCalSounds/' + $_.Name }
foreach ($path in $assetPaths) {
    $original = Join-Path $source $path
    if (-not (Test-Path -LiteralPath $original)) { throw "Missing asset: $path" }
    $hash = (Get-FileHash -LiteralPath $original -Algorithm SHA256).Hash.ToLowerInvariant()
    $assets += [ordered]@{source=$path; sha256=$hash; existing_runtime_paths=@($runtimeHashes[$hash] | Where-Object { $_ }); license='Calamity original terms; see reference/CALAMITY-LICENSE.md'}
}
$skin = Join-Path $workspace 'sample/至尊女巫-灾厄.png'
$skinHash = (Get-FileHash -LiteralPath $skin -Algorithm SHA256).Hash.ToLowerInvariant()
$assets += [ordered]@{source='sample/至尊女巫-灾厄.png'; sha256=$skinHash; existing_runtime_paths=@($runtimeHashes[$skinHash] | Where-Object { $_ }); license='User supplied; unspecified'}
[IO.File]::WriteAllText((Join-Path $output 'resource-audit.json'), ($assets | ConvertTo-Json -Depth 8))
Write-Output "Captured $($manifest.Count) pinned source files; audited $($assets.Count) candidate assets."
